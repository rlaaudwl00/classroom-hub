const assert = require('node:assert/strict');
const { ClassroomTimer, parseDuration, formatTime } = require('./timer.js');
let time = 1000;
const timer = new ClassroomTimer(() => time);
assert.equal(parseDuration('0', '1'), 1000);
assert.equal(parseDuration('99', '59'), 5999000);
for (const input of [['','0'],['0',''],['0','0'],['-1','0'],['1.5','0'],['100','0'],['0','60'],['1e1','0']]) assert.equal(parseDuration(...input), null);
assert.equal(timer.setDuration(60000), true);
assert.equal(timer.start(), true);
const deadline = timer.deadlineMs;
assert.equal(timer.start(), false);
assert.equal(timer.deadlineMs, deadline);
time += 12345; timer.tick(); assert.equal(timer.remainingMs, 47655);
assert.equal(timer.setDuration(10000), false);
timer.pause(); time += 3000; timer.tick(); assert.equal(timer.remainingMs, 47655);
timer.start(); time += 47654; assert.equal(timer.tick(), false); assert.equal(formatTime(timer.remainingMs), '00:01');
time += 1; assert.equal(timer.tick(), true); assert.equal(timer.status, 'finished'); assert.equal(timer.tick(), false);
assert.equal(timer.remainingMs, 0); assert.equal(formatTime(0), '00:00');
timer.start(); assert.equal(timer.remainingMs, 60000); timer.reset(); time += 100000; assert.equal(timer.tick(), false); assert.equal(timer.remainingMs, 60000);
timer.start(); time += 60000; assert.equal(timer.pause(), true); assert.equal(timer.status, 'finished');
timer.reset(); assert.equal(timer.setDuration(0), false); assert.equal(timer.setDuration(5999001), false);
assert.equal(formatTime(5999000), '99:59');
console.log('PASS: input boundaries, deadlines, duplicate start, pause/resume, reset, completion once, delayed tick, formatting.');
